"""Add provenance, weather-only comparison, and grid audit to review results."""
from pathlib import Path
import json
import numpy as np
import pandas as pd
import geopandas as gpd
from shapely.geometry import Point
from sklearn.linear_model import LogisticRegression
from sklearn.metrics import roc_auc_score, average_precision_score, brier_score_loss
from src.dataset import build_dataset, split_by_year

ROOT = Path(__file__).resolve().parent
out = ROOT / "outputs/review_followup.json"
d = json.loads(out.read_text())
frame = build_dataset(ROOT / "data/features")
train, val, test = split_by_year(frame,[2021],[2022],[2023])
def wx(frame):
    return np.column_stack([frame.t_max,1-frame.rh_min,frame.u10_max])
for label,plus_sm in (("weather_only",False),("weather_plus_sm",True)):
    def features(f):
        x = wx(f)
        return np.column_stack([x,1-f.sm_top]) if plus_sm else x
    model=LogisticRegression(max_iter=2000).fit(features(train),train.ignition)
    d["models"][label]={"metrics":{}}
    for name,f in (("validation",val),("test",test)):
        p=model.predict_proba(features(f))[:,1]
        d["models"][label]["metrics"][name]={"auc_roc":float(roc_auc_score(f.ignition,p)),
                                                "auc_pr":float(average_precision_score(f.ignition,p)),
                                                "brier":float(brier_score_loss(f.ignition,p))}
d["weather_plus_sm_test_gain"]=d["models"]["weather_plus_sm"]["metrics"]["test"]["auc_roc"]-d["models"]["weather_only"]["metrics"]["test"]["auc_roc"]

shape = gpd.read_file("zip://"+str(ROOT / "outputs/cb_2024_us_state_500k.zip"))
ca = shape.loc[shape.STUSPS == "CA","geometry"].iloc[0]
cell=frame[["latitude","longitude"]].drop_duplicates()
inside=cell.apply(lambda r:ca.covers(Point(float(r.longitude),float(r.latitude))),axis=1)
d["grid_audit"]={"bounding_box_cells":1600,"cells_with_model_rows":int(len(cell)),
                 "model_cells_inside_california":int(inside.sum()),
                 "model_cells_outside_california":int((~inside).sum()),
                 "california_center_source":"US Census 2024 1:500,000 cartographic state boundary, outputs/cb_2024_us_state_500k.zip"}
d["provenance"]={"status":"observed-source retrospective California hotspot study; source details and hashes in outputs/real_input_audit.json",
                 "ERA5":"36 hourly monthly ERA5 single-level files, primarily from the public Earthmover Icechunk archive, with one sampled grid-point hour checked against CDS in January 2021 and December 2023; 42N--32N and 124W--114W",
                 "FIRMS":"NASA FIRMS VIIRS_SNPP_SP area API historical detections, 2021--2023; nominal/high confidence vegetation detections retained",
                 "MODIS":"NASA LP DAAC AppEEARS MOD13A2.061, 1 km 16-day composites, NDVI/NIR/MIR",
                 "SRTM":"SRTMGL1 elevation GeoTIFFs; 0.25-degree cell slopes generated by build_srtm_slope.py",
                 "lookahead":"MODIS 16-day composite becomes available 16 days after start date; reindex uses forward fill only; hotspot history uses days t-1 through t-7"}
d["methods_audit"]={"ERA5_variables":"t2m, d2m, u10, v10, swvl1; five hourly ERA5 fields",
                    "soil_layer":"swvl1 means top 0-7 cm layer; not root zone",
                    "MODIS_product":"MOD13A2.061, 1 km 16-day composite",
                    "NDWI_formula":"(NIR reflectance - MIR band-7 reflectance)/(NIR + MIR band-7 reflectance + 1e-6)",
                    "VIIRS_product":"VIIRS_SNPP_SP NRT/historical archive via NASA FIRMS area API; type 0 and confidence n/h",
                    "ERA5_aggregation":"daily Tmax, RH computed from T and dew point at Tmax hour, max 10-m wind, mean swvl1; nearest-neighbour regrid",
                    "MODIS_aggregation":"nearest-neighbour spatial sample; 16-day composite held forward after full window elapsed",
                    "SRTM_aggregation":"native-pixel slope in degrees from metre-scaled DEM gradients; cell mean, 0.25 degree",
                    "FIRMS_aggregation":"daily cell hotspot presence; FRP and hotspot counts accumulated separately with weights 0.5^k for k=1..7",
                    "tree_hyperparameters":"RF 200 trees depth 10; XGBoost 200 trees depth 6 learning rate 0.1; LightGBM 200 trees depth 6, 31 leaves, learning rate 0.1",
                    "tree_calibration":"SMOTE to 0.10 then random undersampling to 0.30 on 2021; Platt logistic on 2022 scores/labels",
                    "parameter_counts":"the previous ~10k and ~200 trees descriptions are not defensible parameter counts; report n_estimators/max_depth/num_leaves instead"}
out.write_text(json.dumps(d,indent=2))
print("Updated",out)
